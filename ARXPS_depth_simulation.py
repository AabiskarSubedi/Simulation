import streamlit as st
import numpy as np
import matplotlib.pyplot as plt

st.set_page_config(page_title='ARXPS Simulation', layout='wide')
st.title('Interactive ARXPS Depth Simulation')
st.sidebar.header('Simulation parameters')
lam = st.sidebar.slider('IMFP (nm)', 0.5, 5.0, 2.0, 0.1)
angle = st.sidebar.slider('Emission angle from surface normal (degrees)', 0, 85, 0)
theta = np.deg2rad(angle)
L = lam * np.cos(theta)
d = -np.log(0.05)*L
st.metric('95% information depth', f'{d:.2f} nm')
st.latex(r'd_{95}=-\ln(0.05)\lambda\cos\theta')
fig, (a,b) = plt.subplots(1,2,figsize=(12,5))
a.axhspan(-16,0,color='lightgray')
a.axhspan(-d,0,color='royalblue',alpha=.25)
a.axhline(0,color='black')
a.plot([0,0],[0,9],'k--',label='Surface normal')
x0=-d*np.tan(theta)
a.annotate('',xy=(x0,-d),xytext=(x0-5,8),arrowprops=dict(arrowstyle='->',color='red',lw=2))
a.plot([x0,0],[-d,0],'b--')
a.annotate('',xy=(8*np.sin(theta),8*np.cos(theta)),xytext=(0,0),arrowprops=dict(arrowstyle='->',color='blue',lw=2))
a.plot([],[],color='red',label='Incident X-ray')
a.plot([],[],color='blue',label='Photoelectron')
a.set(xlim=(-21,12),ylim=(-16,12),aspect='equal',title='Measurement geometry',ylabel='Position (nm)')
a.legend(loc='lower right',fontsize=8)
z=np.linspace(0,16,1000)
p=np.exp(-z/L)
b.plot(z,p,label='Survival probability')
b.plot(z,1-p,label='Cumulative signal')
b.axvline(d,color='red',ls='--',label=f'95% depth = {d:.2f} nm')
b.axvspan(0,d,alpha=.15)
b.set(xlabel='Depth (nm)',ylabel='Normalized fraction',title='Photoelectron attenuation',ylim=(0,1.05))
b.grid(alpha=.25)
b.legend()
fig.tight_layout()
st.pyplot(fig)
plt.close(fig)
st.caption('Illustrative homogeneous planar sample model; neglects elastic scattering and photon attenuation.')
